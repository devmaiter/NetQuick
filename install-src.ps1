# ============================================================
#  NetQuick - Install from source (Python + deps)
#  Usage:  irm https://raw.githubusercontent.com/devmaiter/NetQuick/main/install-src.ps1 | iex
#
#  Installs Python (via winget if missing), the dependencies, and
#  downloads the NetQuick files. No need to build an .exe.
# ============================================================
$ErrorActionPreference = "Stop"

$repo   = "devmaiter/NetQuick"
$branch = "main"
$dest   = "$env:LOCALAPPDATA\NetQuick"
$files  = @("netquick.py", "netops.py", "store.py", "winsetup.py", "requirements.txt")

Write-Host ""
Write-Host "  NetQuick - Install from source" -ForegroundColor Cyan
Write-Host ""

# 1) Ensure Python
function Test-Python {
    foreach ($cmd in @("python", "py")) {
        if (Get-Command $cmd -ErrorAction SilentlyContinue) { return $cmd }
    }
    return $null
}

$py = Test-Python
if (-not $py) {
    Write-Host "  Python not found. Installing with winget..." -ForegroundColor Yellow
    if (-not (Get-Command winget -ErrorAction SilentlyContinue)) {
        throw "winget is not available. Install Python 3.8+ manually from python.org and retry."
    }
    winget install -e --id Python.Python.3.12 --silent --accept-source-agreements --accept-package-agreements
    Write-Host "  Python installed. IMPORTANT: close and open a NEW terminal, then re-run this command." -ForegroundColor Yellow
    return
}
Write-Host "  Python detected ($py)." -ForegroundColor Green

# 2) Destination folder and file download
New-Item -ItemType Directory -Force -Path $dest | Out-Null
$base = "https://raw.githubusercontent.com/$repo/$branch"
foreach ($f in $files) {
    Write-Host "  Downloading $f..." -ForegroundColor Gray
    Invoke-WebRequest -Uri "$base/$f" -OutFile "$dest\$f" -UseBasicParsing
}

# 3) Install dependencies
Write-Host "  Installing dependencies..." -ForegroundColor Gray
& $py -m pip install --quiet --upgrade pip
& $py -m pip install --quiet -r "$dest\requirements.txt"

# 4) Launchers with the REAL path to pythonw.exe (independent of the PATH).
#    A bare "pythonw" fails silently if the machine has "py" but no
#    "pythonw" on the PATH (issue #12).
$realPy  = (& $py -c "import sys; print(sys.executable)").Trim()
$pythonw = Join-Path (Split-Path $realPy) "pythonw.exe"
if (-not (Test-Path $pythonw)) { $pythonw = $realPy }  # last resort: with a console

$launcher = "$dest\netquick.cmd"
"@echo off`r`nstart `"`" `"$pythonw`" `"$dest\netquick.py`" %*" | Set-Content -Path $launcher -Encoding ASCII

# Double-click .vbs launcher, generated with absolute paths
$vbsContent = @"
' Launcher generated by install-src.ps1 (absolute paths, PATH-independent)
Set sh = CreateObject("WScript.Shell")
sh.Run """$pythonw"" ""$dest\netquick.py""", 0, False
"@
Set-Content -Path "$dest\NetQuick.vbs" -Value $vbsContent -Encoding ASCII

# 5) Add to the user PATH
$userPath = [Environment]::GetEnvironmentVariable("Path", "User")
if ($userPath -notlike "*$dest*") {
    [Environment]::SetEnvironmentVariable("Path", "$userPath;$dest", "User")
}

Write-Host ""
Write-Host "  Installed at: $dest" -ForegroundColor Green
Write-Host "  Open a NEW terminal and type: netquick" -ForegroundColor White
Write-Host "  (run it as Administrator to change the network)" -ForegroundColor Yellow
Write-Host ""
